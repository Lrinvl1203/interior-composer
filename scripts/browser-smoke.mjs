// Browser integration proof against the explicit offline fixture server only.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../frontend/package.json', import.meta.url));
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, '.local', 'qa');
const base = process.env.COMPOSER_SMOKE_URL || 'http://127.0.0.1:3102';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
page.setDefaultTimeout(12000);
const errors = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
function record(name) { checks.push({ name, passed: true }); console.log('PASS '+name); }
try {
  const health = await page.request.get(base + '/api/health');
  assert.equal(health.headers()['x-composer-qa-fixture'], 'offline-not-ai', 'Refuse to generate against a real provider/server');
  await page.goto(base + '/tools/interior-composer');
  await page.getByText('이 브라우저에 저장됨', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'After 부분 합성 시작', exact: true }).isDisabled());
  assert(await page.getByText('저장된 에셋이 없습니다.', { exact: true }).isVisible());
  record('Empty standalone workspace');
  await page.locator('input[type=file]').nth(1).setInputFiles(path.join(root, '.local', 'smoke-data', 'before.png'));
  await page.getByRole('button', { name: /세이지그린 · 예시/ }).click();
  const initialRequest = 'OFFLINE QA FIXTURE: 벽만 변경하고 기존 가구와 구도를 유지합니다.';
  await page.getByLabel('추가 요청', { exact: false }).fill(initialRequest);
  await page.getByRole('button', { name: 'After 부분 합성 시작', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  record('Native confirmation and Escape cancellation');
  await page.getByRole('button', { name: 'After 부분 합성 시작', exact: true }).click();
  const posted = page.waitForResponse(r => r.url().endsWith('/api/interior-compose') && r.request().method() === 'POST');
  await page.getByRole('dialog').getByRole('button', { name: '이 설정으로 적용', exact: true }).click();
  const job = await (await posted).json();
  assert(job.job_id);
  await page.getByText('합성과 검수가 완료되었습니다. 보고서를 저장할 수 있습니다.', { exact: true }).waitFor({ timeout: 25000 });
  record('Multipart upload through real Next proxy + fixture worker');
  const reportPosted = page.waitForResponse(r => r.url().endsWith('/api/interior-reports') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '상담 보고서 생성', exact: true }).click();
  const report = await (await reportPosted).json();
  assert(report.report_id);
  await page.getByRole('link', { name: '웹 보고서 열기', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, '02-offline-result-report.png'), fullPage: true });
  record('Web report creation');
  await page.getByLabel('추가 요청', { exact: false }).fill('생성 후 편집 · 보고서 정본과 달라야 합니다.');
  const nextReportPosted = page.waitForResponse(r => r.url().endsWith('/api/interior-reports') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '새 보고서 버전 저장', exact: true }).click();
  const nextReport = await (await nextReportPosted).json();
  assert.equal(nextReport.version, 2);
  const canonical = await (await page.request.get(base+'/api/interior-reports/'+nextReport.report_id)).json();
  assert.equal(canonical.request, initialRequest);
  record('Version2 preserves original generation request');
  await page.getByText('이 브라우저에 저장됨', { exact: true }).waitFor();
  await page.reload();
  await page.getByRole('link', { name: '웹 보고서 열기', exact: true }).waitFor();
  assert.equal(await page.getByLabel('추가 요청', { exact: false }).inputValue(), '생성 후 편집 · 보고서 정본과 달라야 합니다.');
  record('Photo/result/report/draft reload persistence');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'PDF 다운로드', exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs(path.join(output, 'offline-report.pdf'));
  assert.equal((await fs.readFile(path.join(output, 'offline-report.pdf'))).subarray(0,4).toString(), '%PDF');
  record('Actual PDF download');
  const reportPage = await context.newPage();
  await reportPage.goto(base+nextReport.share_url);
  await reportPage.getByRole('heading', { name: /인테리어 상담 보고서/ }).waitFor();
  await reportPage.screenshot({ path: path.join(output, '03-offline-web-report.png'), fullPage: true });
  record('Report page opens independently');
  const second = await context.newPage();
  await second.goto(base+'/tools/interior-composer');
  await second.getByText('이 브라우저에 저장됨', { exact: true }).waitFor();
  await second.getByLabel('추가 요청', { exact: false }).fill('두 번째 탭 최신 초안 · 보존');
  await second.getByText('이 브라우저에 저장됨', { exact: true }).waitFor();
  await page.getByLabel('추가 요청', { exact: false }).fill('오래된 탭 저장 시도');
  await page.getByText('다른 탭에서 더 최신 작업을 저장했습니다. 덮어쓰지 않고 자동 저장을 멈췄습니다.', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'After 부분 합성 시작', exact: true }).isDisabled());
  await second.reload();
  await second.getByText('이 브라우저에 저장됨', { exact: true }).waitFor();
  assert.equal(await second.getByLabel('추가 요청', { exact: false }).inputValue(), '두 번째 탭 최신 초안 · 보존');
  record('Stale tab cannot overwrite newer draft');
  await page.screenshot({ path: path.join(output, '04-two-tab-conflict.png'), fullPage: true });
  await page.getByRole('button', { name: '최신 저장본 불러오기', exact: true }).click();
  await page.getByText('이 브라우저에 저장됨', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('추가 요청', { exact: false }).inputValue(), '두 번째 탭 최신 초안 · 보존');
  record('Explicit latest-draft recovery');
  for (const width of [320, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'Horizontal overflow '+width);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('a[href="#composer-step-2"]').click();
  await page.screenshot({ path: path.join(output, '05-mobile.png'), fullPage: true });
  record('320/768/1440 responsive overflow checks');
  assert.deepEqual(errors, []);
  record('No browser page errors');
  await fs.writeFile(path.join(output, 'browser-evidence.json'), JSON.stringify({ fixture:true, realAiCalls:0, checks, reportId:nextReport.report_id, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, checks: checks.length, fixture:true, realAiCalls:0 }));
} catch (error) {
  await page.screenshot({ path: path.join(output, 'FAILED.png'), fullPage: true }).catch(()=>{});
  console.error(error);
  process.exitCode = 1;
} finally { await browser.close(); }
